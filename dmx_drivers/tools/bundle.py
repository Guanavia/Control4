#!/usr/bin/env python3
"""Bundle a driver's main.lua and every module it requires into one driver.lua.

Modules are looked up in the driver's own folder first, then common/. Each module becomes a
function in a local table, and a LOCAL `require` resolves them, so the bundle does not depend on
Director's package/require support at all. Module bodies are copied verbatim (not re-indented) so
line numbers in errors stay close to the source.

usage: bundle.py <driver_dir> <out_file>
"""
import os
import re
import sys

REQUIRE = re.compile(r'''\brequire\s*\(?\s*["']([\w\.]+)["']\s*\)?''')


def find(name, driver_dir, common_dir):
    for d in (driver_dir, common_dir):
        path = os.path.join(d, name.replace('.', '/') + '.lua')
        if os.path.exists(path):
            return path
    return None


def strip_comments(src):
    src = re.sub(r'--\[\[.*?\]\]', '', src, flags=re.S)
    return re.sub(r'--[^\n]*', '', src)


def main():
    driver_dir, out = sys.argv[1], sys.argv[2]
    common_dir = os.path.join(os.path.dirname(os.path.abspath(driver_dir)), 'common')
    main_path = os.path.join(driver_dir, 'main.lua')
    order, seen = [], set()

    def visit(name, path, chain):
        src = open(path, encoding='utf-8').read()
        for dep in REQUIRE.findall(strip_comments(src)):
            if dep in chain:
                sys.exit('ERROR: circular require %s -> %s' % (' -> '.join(chain), dep))
            if dep in seen:
                continue
            dep_path = find(dep, driver_dir, common_dir)
            if not dep_path:
                sys.exit('ERROR: %s requires "%s", which is in neither %s nor common/' % (path, dep, driver_dir))
            seen.add(dep)
            visit(dep, dep_path, chain + [dep])
            order.append((dep, dep_path))

    visit('main', main_path, ['main'])

    parts = [
        '-- %s/driver.lua -- GENERATED by tools/bundle.py from main.lua + modules. Do not edit;\n'
        '-- edit the sources in dmx_drivers/ and rebuild.\n' % os.path.basename(os.path.normpath(driver_dir)),
        'local __MODULES, __LOADED = {}, {}\n'
        'local function require(name)\n'
        '  local m = __LOADED[name]\n'
        '  if m ~= nil then return m end\n'
        '  local f = __MODULES[name]\n'
        '  if not f then error("module not bundled: " .. tostring(name)) end\n'
        '  m = f(name)\n'
        '  if m == nil then m = true end\n'
        '  __LOADED[name] = m\n'
        '  return m\n'
        'end\n',
    ]
    for name, path in order:
        rel = os.path.relpath(path, os.path.dirname(os.path.abspath(driver_dir)))
        body = open(path, encoding='utf-8').read().rstrip('\n')
        parts.append('\n-- ===== module %s (%s) =====\n__MODULES["%s"] = function(...)\n%s\nend\n' % (name, rel, name, body))
    parts.append('\n-- ===== main (%s/main.lua) =====\n' % os.path.basename(os.path.normpath(driver_dir)))
    parts.append(open(main_path, encoding='utf-8').read())
    open(out, 'w', encoding='utf-8').write(''.join(parts))
    print('bundled %s: %d module(s): %s' % (driver_dir, len(order), ', '.join(n for n, _ in order)))


if __name__ == '__main__':
    main()
